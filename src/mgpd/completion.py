"""Generate native Bash/Zsh completion from the CLI's argparse definition."""
import argparse
import shlex


def command_parsers(parser):
    action = next(action for action in parser._actions if isinstance(action, argparse._SubParsersAction))
    descriptions = {item.dest: '' if item.help == argparse.SUPPRESS else item.help
                    for item in action._choices_actions}
    return action.choices, descriptions


def value_kind(command, action):
    if action.choices is not None:
        return 'choices'
    if command == 'validate-config' and action.dest == 'directory':
        return 'files'
    if action.dest in ('directory', 'copy', 'base_directory', 'from_results'):
        return 'directories'
    if action.dest == 'output':
        return 'files' if command == 'merge' else 'directories'
    if action.dest in ('project', 'inputs', 'image', 'config'):
        return 'files'
    return 'none'


def bash_completion(parser):
    commands, _ = command_parsers(parser)
    roots = [option for action in parser._actions for option in action.option_strings]
    root_words = ' '.join([*commands, *roots])
    options, values, positionals = [], [], []
    for name, command in commands.items():
        flags = [option for action in command._actions for option in action.option_strings]
        taking = [option for action in command._actions if action.nargs != 0 for option in action.option_strings]
        repeat = any(not action.option_strings and action.nargs in ('*', '+') for action in command._actions)
        options.append(f'        {name}) flags={shlex.quote(" ".join(flags))}; taking={shlex.quote(" ".join(taking))}; repeat={int(repeat)} ;;')
        for action in command._actions:
            if not action.option_strings:
                kind = value_kind(name, action)
                if kind in ('directories', 'files'):
                    positionals.append(f'        {name}) kind={kind} ;;')
                elif action.choices is not None:
                    positionals.append(f'        {name}) choices={shlex.quote(" ".join(action.choices))} ;;')
            elif action.nargs != 0:
                pattern = '|'.join(name + ':' + option for option in action.option_strings)
                kind = value_kind(name, action)
                choices = ' '.join(str(value) for value in action.choices) if action.choices is not None else ''
                values.append(f'        {pattern}) kind={kind}; choices={shlex.quote(choices)} ;;')
    return '''# Generated by mgpd completion bash. Compatible with Bash 3.2+.
_mgpd_complete() {
    local cur prev command flags kind choices option prefix candidate taking repeat count expect ended i word
    COMPREPLY=()
    cur=${COMP_WORDS[COMP_CWORD]}
    prev=${COMP_WORDS[COMP_CWORD-1]}
    command=${COMP_WORDS[1]}
    if [ "$COMP_CWORD" -le 1 ]; then
        while IFS= read -r candidate; do COMPREPLY+=("$candidate"); done < <(compgen -W ROOT_WORDS -- "$cur")
        return 0
    fi
    flags=''
    taking=''
    repeat=0
    count=0
    expect=0
    ended=0
    case "$command" in
OPTIONS
    esac
    for ((i=2; i<COMP_CWORD; i++)); do
        word=${COMP_WORDS[i]}
        if [ "$expect" = 1 ]; then
            [ "$word" = '=' ] && continue
            expect=0
            continue
        fi
        if [ "$ended" = 0 ]; then
            if [ "$word" = '--' ]; then ended=1; continue; fi
            if [[ "$word" == -* ]]; then
                case " $taking " in *" $word "*) expect=1 ;; esac
                continue
            fi
        fi
        count=$((count+1))
    done
    kind=''
    choices=''
    option=$prev
    prefix=''
    # Handle both shells that split '=' in COMP_WORDS and unsplit --opt=value.
    if [[ "$cur" == --*=* ]]; then
        option=${cur%%=*}
        prefix=$option=
        cur=${cur#*=}
    elif [ "$prev" = '=' ] && [ "$COMP_CWORD" -ge 2 ]; then
        option=${COMP_WORDS[COMP_CWORD-2]}
    elif [ "$cur" = '=' ]; then
        cur=''
    fi
    if [ "$ended" = 0 ]; then
        case "$command:$option" in
VALUES
        esac
    fi
    if [ -z "$kind" ]; then
        if [ "$ended" = 0 ] && { [[ "$cur" == -* ]] || { [ "$count" -gt 0 ] && [ "$repeat" = 0 ]; }; }; then
            choices=$flags
        else
            if [ "$count" -gt 0 ] && [ "$repeat" = 0 ]; then return 0; fi
            case "$command" in
POSITIONALS
            esac
        fi
    fi
    if [ -n "$choices" ]; then
        while IFS= read -r candidate; do COMPREPLY+=("$prefix$candidate"); done < <(compgen -W "$choices" -- "$cur")
    elif [ "$kind" = directories ]; then
        while IFS= read -r candidate; do COMPREPLY+=("$prefix$candidate"); done < <(compgen -d -- "$cur")
    elif [ "$kind" = files ]; then
        while IFS= read -r candidate; do COMPREPLY+=("$prefix$candidate"); done < <(compgen -f -- "$cur")
    fi
    return 0
}
complete -o filenames -F _mgpd_complete mgpd
'''.replace('ROOT_WORDS', shlex.quote(root_words)).replace('OPTIONS', '\n'.join(options)).replace('VALUES', '\n'.join(values)).replace('POSITIONALS', '\n'.join(positionals))


def zsh_description(value):
    value = '' if value == argparse.SUPPRESS else value
    return (value or '').replace('\\', '\\\\').replace('[', '\\[').replace(']', '\\]').replace(':', '\\:').replace('\n', ' ')


def zsh_completion(parser):
    commands, descriptions = command_parsers(parser)
    root_options = []
    for action in parser._actions:
        for option in action.option_strings:
            root_options.append(shlex.quote(option + '[' + zsh_description(action.help) + ']'))
    cases = []
    for name, command in commands.items():
        specs = []
        index = 0
        for action in command._actions:
            kind = value_kind(name, action)
            if kind == 'choices':
                complete = '(' + ' '.join(str(value) for value in action.choices) + ')'
            else:
                complete = {'directories': '_directories', 'files': '_files', 'none': ''}[kind]
            if action.option_strings:
                for option in action.option_strings:
                    repeat = '*' if isinstance(action, argparse._AppendAction) else ''
                    argument = '=' if option.startswith('--') and action.nargs != 0 else ''
                    spec = repeat + option + argument + '[' + zsh_description(action.help) + ']'
                    if action.nargs != 0:
                        spec += ':' + action.dest + ':' + complete
                    specs.append(shlex.quote(spec))
            else:
                index += 1
                prefix = '*' if action.nargs in ('*', '+') else str(index)
                specs.append(shlex.quote(prefix + ':' + action.dest + ':' + complete))
        cases.append(f'        {name})\n            _arguments -s -S \\\n                ' + ' \\\n                '.join(specs) + '\n            ;;')
    command_specs = ' '.join(shlex.quote(name + ':' + descriptions[name]) for name in commands)
    return '''# Generated by mgpd completion zsh. Run compinit before sourcing.
_mgpd() {
    local context state state_descr line
    typeset -A opt_args
    _arguments -C ROOT_OPTIONS \\
        '1:command:->command' \\
        '*::arguments:->arguments'
    case "$state" in
    command)
        local -a commands
        commands=(COMMAND_SPECS)
        _describe 'mgpd command' commands
        ;;
    arguments)
        case "$line[1]" in
CASES
        esac
        ;;
    esac
}
compdef _mgpd mgpd
'''.replace('ROOT_OPTIONS', ' '.join(root_options)).replace('COMMAND_SPECS', command_specs).replace('CASES', '\n'.join(cases))


def shell_completion(parser, shell):
    if shell == 'bash':
        return bash_completion(parser)
    if shell == 'zsh':
        return zsh_completion(parser)
    raise ValueError('Supported shells: bash, zsh')
